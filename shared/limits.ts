/**
 * @file limits.ts
 * @description 入口字数上限的单一来源。
 *
 * ## 为什么要单独抽出来
 *
 * 这个数字原先散落在四处：解析契约（`parse-contract.ts`）、解读契约
 * （`interpret-contract.ts`）、公众号抓取截断（`article-extract.mjs`）、
 * 前端材料预算（`ParsePage` 的 `MATERIAL_BUDGET`）。
 *
 * 四个地方各写一遍的后果不是打错字，是**口径互相矛盾**：只把解析上限调大、
 * 忘了抓取截断，用户就会遇到「能解析 5 万字，但抓回来的文章只到 2 万字」——
 * 而且他不会收到任何提示，只会觉得「这篇文章怎么少了一半」。
 *
 * ## 为什么是 50000
 *
 * 不是模型撑不住。2 万字中文约 1.3 万–2 万 token，主流服务商上下文 64K 起，
 * 连三分之一都没占到；本项目的规则库上下文本来就允许 6 万字进模型。
 *
 * 真正的原因是**准确性**。这个应用的立身之本是「日期不瞎猜、证据逐字校验」。
 * 文中越长，模型越容易把「报名截止 12 点」和「活动开始 20 点」搞混——
 * 那正是 G6 样本专门要防的错。所以这个数字是一条**护栏**，不是天花板：
 * 宁可让超出的部分被明确告知、由人决定要不要拆开，也不让模型在长文里
 * 自信地挑错日期。
 *
 * 5 万这个取值覆盖了「一份完整手册 + 若干补充材料」，同时把单次解析的
 * 注意力成本控制在可接受范围。真实通知通常 1000–3000 字，正常使用碰不到。
 */
export const MAX_NOTIFICATION_CHARS = 50000;
